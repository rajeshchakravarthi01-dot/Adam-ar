export const DEFAULT_SENDER_EMAIL = 'ashutosh.kumar@auditeq.com';
export const FATAL_CC_EMAIL = 'sambath.s@fundsindia.com';

function cleanName(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

export function findAdvisorEntry(dealer?: string | null, advisorName?: string | null): FundsIndiaAdvisorEntry | null {
  if (dealer) {
    const cleanDealer = dealer.trim().toUpperCase();
    const found = FUNDSINDIA_ADVISOR_DIRECTORY.find((a) => a.dealer.toUpperCase() === cleanDealer);
    if (found) return found;
  }

  if (advisorName) {
    const cleaned = cleanName(advisorName);
    if (!cleaned) return null;

    let found = FUNDSINDIA_ADVISOR_DIRECTORY.find((a) => cleanName(a.advisor_name) === cleaned);
    if (found) return found;

    found = FUNDSINDIA_ADVISOR_DIRECTORY.find(
      (a) => cleanName(a.advisor_name).includes(cleaned) || cleaned.includes(cleanName(a.advisor_name))
    );
    if (found) return found;
  }

  return null;
}

export function getAdvisorEmailRouting(options: {
  advisorName?: string | null;
  dealer?: string | null;
  isFatalAlone?: boolean;
}): { to: string; cc: string } {
  const { advisorName, dealer, isFatalAlone } = options;
  const entry = findAdvisorEntry(dealer, advisorName);

  let to = entry?.to_email || '';
  if (!to && advisorName) {
    to = `${advisorName.toLowerCase().replace(/[^a-z0-9]/g, '.')}@auditeq.com`;
  }

  const ccSet = new Set<string>();
  if (entry && entry.cc_emails.length > 0) {
    entry.cc_emails.forEach((e) => ccSet.add(e.trim().toLowerCase()));
  }

  // Sambath S rule: only include sambath.s@fundsindia.com when sending only fatals (0 marks)!
  if (isFatalAlone) {
    ccSet.add(FATAL_CC_EMAIL.toLowerCase());
  } else {
    ccSet.delete(FATAL_CC_EMAIL.toLowerCase());
    ccSet.delete('sambath.s@auditeq.com');
  }

  return {
    to,
    cc: Array.from(ccSet).join(', '),
  };
}
